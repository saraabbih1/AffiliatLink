
CREATE TABLE offers (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        advertiser_id BIGINT NOT NULL,
                        title VARCHAR(150) NOT NULL,
                        description TEXT,
                        landing_url VARCHAR(2048) NOT NULL,
                        niche VARCHAR(100) NOT NULL,
                        created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL
);

CREATE TABLE tags (
                      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                      name VARCHAR(50) NOT NULL,
                      CONSTRAINT uk_tags_name UNIQUE (name)
);

CREATE TABLE offer_tags (
                            offer_id BIGINT NOT NULL,
                            tag_id BIGINT NOT NULL,

                            CONSTRAINT pk_offer_tags PRIMARY KEY (offer_id, tag_id),
                            CONSTRAINT fk_offer_tags_offer
                                FOREIGN KEY (offer_id) REFERENCES offers(id) ON DELETE CASCADE,
                            CONSTRAINT fk_offer_tags_tag
                                FOREIGN KEY (tag_id) REFERENCES tags(id) ON DELETE CASCADE
);

CREATE TABLE campaigns (
                           id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                           name VARCHAR(150) NOT NULL,
                           start_date DATE NOT NULL,
                           end_date DATE NOT NULL,
                           budget NUMERIC(12, 2) NOT NULL,
                           payout_model VARCHAR(20) NOT NULL,
                           payout_value NUMERIC(12, 2) NOT NULL,
                           status VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
                           offer_id BIGINT NOT NULL,

                           CONSTRAINT fk_campaigns_offer
                               FOREIGN KEY (offer_id) REFERENCES offers(id),

                           CONSTRAINT chk_campaigns_dates
                               CHECK (end_date > start_date),

                           CONSTRAINT chk_campaigns_budget
                               CHECK (budget > 0),

                           CONSTRAINT chk_campaigns_payout_model
                               CHECK (payout_model IN ('CPC', 'CPL', 'CPA_FIXED', 'CPA_PERCENT')),

                           CONSTRAINT chk_campaigns_payout_value
                               CHECK (
                                   (payout_model IN ('CPC', 'CPL', 'CPA_FIXED') AND payout_value > 0)
                                       OR
                                   (payout_model = 'CPA_PERCENT' AND payout_value BETWEEN 0 AND 100)
                                   ),

                           CONSTRAINT chk_campaigns_status
                               CHECK (status IN ('DRAFT', 'ACTIVE', 'PAUSED', 'ENDED'))
);

CREATE UNIQUE INDEX uq_campaigns_one_active_per_offer
    ON campaigns (offer_id)
    WHERE status = 'ACTIVE';
